const std = @import("std");

test "table covers printable ascii" {
    try std.testing.expectEqual(@as(usize, 95), table.len);
    try std.testing.expect(glyph(' ') != null);
    try std.testing.expect(glyph('~') != null);
    try std.testing.expect(glyph(0x1f) == null);
    try std.testing.expect(glyph(0x7f) == null);
}

test "space is blank, every other glyph has ink" {
    for (table[0]) |row| try std.testing.expectEqual(@as(Row, 0), row);
    for (table[1..]) |g| {
        var any = false;
        for (g) |row| any = any or row != 0;
        try std.testing.expect(any);
    }
}

test "pixel() reads columns left to right" {
    const a = glyph('A').?;
    // Row 5 of 'A' is the crossbar: .#####.
    try std.testing.expect(!pixel(a, 0, 5));
    try std.testing.expect(pixel(a, 1, 5));
    try std.testing.expect(pixel(a, 5, 5));
    try std.testing.expect(!pixel(a, 6, 5));
}

test "descenders live below the baseline" {
    for ("gjpqy") |ch| {
        const g = glyph(ch).?;
        var below = false;
        for (g[baseline..]) |row| below = below or row != 0;
        try std.testing.expect(below);
    }
}
