const Font = @This();

pub const width = 7;
pub const height = 11;
pub const baseline = 9;
pub const line_height = 14;

pub const cap_height = 8;
pub const x_height = 6;

pub const first_char: u8 = ' ';
pub const last_char: u8 = '~';

pub const Row = u7;
pub const Glyph = [height]Row;

pub fn glyph(ch: u8) ?Glyph {
    if (ch < first_char or ch > last_char) return null;
    return table[ch - first_char];
}

pub fn pixel(g: Glyph, x: usize, y: usize) bool {
    if (x >= width or y >= height) return false;
    return (g[y] >> @intCast(width - 1 - x)) & 1 != 0;
}

